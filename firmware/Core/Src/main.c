uint16_t low_pass_filter(uint16_t input) {
    static uint16_t previous_output = 0;
    previous_output = (previous_output * 15 + input) / 16;
    return previous_output;
}

uint16_t moving_average_filter(uint16_t input) {
    static uint32_t sum = 0;
    sum -= moving_average_buffer[buffer_index];
    moving_average_buffer[buffer_index] = input;
    sum += input;
    buffer_index = (buffer_index + 1) % MOVING_AVERAGE_WINDOW;
    return sum / MOVING_AVERAGE_WINDOW;
}

uint16_t remove_spikes(uint16_t input) {
    uint16_t derivative = abs(input - previous_value);
    previous_value = input;

    if (derivative > DERIVATIVE_THRESHOLD) {
        return previous_value;
    }
    return input;
}

uint16_t remove_outliers(uint16_t input) {
    static uint16_t values[MOVING_AVERAGE_WINDOW];
    static uint8_t index = 0;
    values[index] = input;
    index = (index + 1) % MOVING_AVERAGE_WINDOW;

    uint16_t sorted[MOVING_AVERAGE_WINDOW];
    memcpy(sorted, values, sizeof(values));
    for (int i = 0; i < MOVING_AVERAGE_WINDOW - 1; i++) {
        for (int j = i + 1; j < MOVING_AVERAGE_WINDOW; j++) {
            if (sorted[i] > sorted[j]) {
                uint16_t temp = sorted[i];
                sorted[i] = sorted[j];
                sorted[j] = temp;
            }
        }
    }

    uint16_t q1 = sorted[MOVING_AVERAGE_WINDOW / 4];
    uint16_t q3 = sorted[3 * MOVING_AVERAGE_WINDOW / 4];
    uint16_t iqr = q3 - q1;
    uint16_t lower_bound = q1 - OUTLIER_THRESHOLD * iqr;
    uint16_t upper_bound = q3 + OUTLIER_THRESHOLD * iqr;

    uint16_t median = sorted[MOVING_AVERAGE_WINDOW / 2];
    if (input < lower_bound || input > upper_bound) {
        return median;
    }
    return input;
}

uint32_t square_signal(uint16_t input) {
    return (uint32_t)input * (uint32_t)input;
}

void detect_r_peak(uint16_t input, int16_t derivative) {
    static uint8_t peak_detected = 0;
    static uint16_t refractory_counter = 0;

    if (refractory_counter > 0) {
            refractory_counter--;
            return;
        }

    if (input > R_PEAK_THRESHOLD) {
        if (!peak_detected) {
        	increment_affichage+=1;
            HAL_GPIO_WritePin(GPIOB, LED_Pin, GPIO_PIN_SET);
            HAL_TIM_Base_Start_IT(&htim6);

            uint32_t peak_period = __HAL_TIM_GET_COUNTER(&htim7);
            bpm = 600000/peak_period;

            if (increment_affichage == 3) {
            	sprintf(MSG, "BPM %3ld", bpm);
            	increment_affichage = 0;
            }


            __HAL_TIM_SET_COUNTER(&htim7, 0);
            peak_detected = 1;
            refractory_counter = REFRACTORY_PERIOD;
        }
    }
    else if (previous_derivative < 0 && derivative > 0) {
        peak_detected = 0;
    }

    previous_derivative = derivative;
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc) {
    if (hadc->Instance == ADC1) {

        uint16_t adc_value = HAL_ADC_GetValue(&hadc1);
        uint16_t filtered_value = square_signal(moving_average_filter(low_pass_filter(remove_outliers(remove_spikes(adc_value)))));
        int16_t derivative = filtered_value - previous_value;
        previous_value = filtered_value;

        detect_r_peak(filtered_value, derivative);

        sprintf(buffer, "%d\r\n", filtered_value);
        HAL_UART_Transmit(&huart1, (uint8_t*)buffer, strlen(buffer), HAL_MAX_DELAY);

        HAL_ADC_Start_IT(&hadc1);
    }
}

